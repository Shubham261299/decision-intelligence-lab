"""Offline portfolio introduction; observations come only from saved reports."""

from pathlib import Path

import streamlit as st

from app import research_data as data
from app.presentation import render_table
from app.research_dashboard import INTERPRETATIONS

QUESTION = "How can we make LLM-based decision making more measurable, structured, explainable and reliable?"


def navigate(page: str) -> None:
    """Widget callback runs before the sidebar selector on the next rerun."""
    if page not in ("Overview", "Decision Playground", "Research Dashboard"):
        raise ValueError("Unknown workspace")
    st.session_state["page"] = page


def render_overview(root: Path | None = None) -> None:
    root = root if root is not None else data.ROOT
    st.caption("DECISION INTELLIGENCE LAB / EVALUATION-FIRST RESEARCH")
    st.title("Beyond generation. Measure the decision.")
    st.markdown(f"### {QUESTION}")
    st.write("DecisionLab makes decision outputs inspectable: explicit options, constraints, "
             "abstention, evidence references and independent evaluation. This portfolio "
             "connects a small Python framework to reproducible local experiments.")
    first, second = st.columns(2)
    with first:
        st.button("Open Decision Playground", type="primary", on_click=navigate,
                  args=("Decision Playground",), key="open-playground", use_container_width=True)
        st.caption("Inspect an offline synthetic decision, its policy checks and verifier findings.")
    with second:
        st.button("Explore Research Dashboard", on_click=navigate,
                  args=("Research Dashboard",), key="open-research", use_container_width=True)
        st.caption("Read recorded comparisons, failures and provenance. No models are called.")
    st.divider()
    st.subheader("A framework for inspectable decisions")
    sections = [
        ("Decision strategies", "Compare a deterministic rule baseline, direct-text and structured LLM pipelines. Bounded tool-assisted decisions expose explicit tool evidence; they are not autonomous agents."),
        ("Evaluation and benchmark design", "Frozen synthetic routing inputs and separate reference expectations support selection, abstention and failure scoring. Expected answers never become strategy inputs."),
        ("Policy checks and abstention", "Explicit routing and capacity rules remain separate from generation. Missing material information can require abstention; a valid selection can still require human review."),
        ("Verification and evidence references", "A verifier checks a produced recommendation without making the original decision. Resolvable citations are distinct from evidence that actually supports a claim."),
        ("Confidence and robustness", "Measure available confidence against outcomes without treating it as calibrated. Separate stability experiments test equivalent inputs; stability does not imply accuracy."),
        ("Reproducible experiments and provenance", "Versioned prompts, frozen benchmark hashes, recorded settings and preserved failures make experimental conditions inspectable. Historical results are not regenerated by this app."),
    ]
    for index in range(0, len(sections), 2):
        columns = st.columns(2)
        for column, (title, description) in zip(columns, sections[index:index + 2]):
            with column:
                with st.container(border=True):
                    st.markdown(f"#### {title}")
                    st.write(description)
    st.subheader("Methodology & architecture")
    st.write("DecisionProblem → strategy → typed Recommendation → shared policy → separate verifier result")
    st.caption("Independent benchmark evaluation compares outputs with separate references. "
               "Diagnostic inspection and human review never repair outputs or change primary scores. "
               "The presentation layer reads results; it does not redefine decision logic.")
    st.divider()
    st.subheader("What the experiments show")
    st.caption("Observations below are read from saved artifacts, with development and held-out results kept separate. "
               "Interpretations are sourced from docs/research-findings.md, not inferred from missing reports.")
    documented = (root / "docs/research-findings.md").is_file()
    titles = {
        "Strategy comparison": "1 / Strategy comparison",
        "JSON enforcement": "2 / Matched JSON enforcement",
        "Output representation": "3 / Matched output representation",
    }
    for experiment, splits in data.COMPARISONS.items():
        with st.container(border=True):
            st.markdown(f"#### {titles[experiment]}")
            for split, relative in splits.items():
                loaded = data.load_comparison(root, relative)
                st.caption(f"Observation / {split} / {relative}")
                if loaded.data is None:
                    st.warning(loaded.error)
                    continue
                report = loaded.data
                st.caption(f"{len(report.case_ids)} cases; {report.repeats} repetition(s).")
                render_table([
                    {"Strategy / condition": name,
                     "Overall correctness": data.rate_text(column.report.summary.rates.get("outcome_correctness")),
                     "Execution failures": data.rate_text(column.report.summary.rates.get("execution_failure_rate"))}
                    for name, column in report.columns.items()
                ])
            if documented:
                st.markdown("**Documented interpretation**")
                st.write(INTERPRETATIONS[experiment])
            else:
                st.caption("Documented interpretation unavailable: docs/research-findings.md is missing.")
    st.caption("Experiments 1 and 2 have no prospectively preserved raw-response records. "
               "Experiment 3 preserves raw responses where returned; a provider timeout cannot be reconstructed. "
               "Open the Research Dashboard for paired outcomes, diagnostic analysis and evidence availability.")
    st.subheader("Research boundaries")
    st.warning("Small synthetic benchmark, not production certification. The held-out split is a "
               "development holdout with public labels, not an independent blind test.")
    st.write("Structural validity, valid evidence references and verifier acceptance do not establish "
             "semantic evidence support or factual correctness. Confidence is uncalibrated; "
             "related cases and repetitions are not independent samples.")
    st.caption("Accepted first-pass review is user-accepted and assistant-assisted, not independent blind expert validation. "
               "No general superiority or statistical-significance claim follows from these experiments.")
    st.markdown("**Untested hypothesis**")
    st.write("Representation-induced generation, output instructions and parser rigidity may interact. "
             "The experiments do not isolate a pure parser-only causal effect.")
    st.caption("GitHub repository: pending manual confirmation in project configuration or documentation. "
               "No unverified repository link is published here.")
